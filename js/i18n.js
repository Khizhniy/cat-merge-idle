function T(s){
  if (LANG !== "en" || s == null) return s;
  const str = String(s), key = str.trim(), v = EN_DICT[key];
  if (v === undefined) return str;
  return str.slice(0, str.length - str.trimStart().length) + v + str.slice(str.trimEnd().length);
}
