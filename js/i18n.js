function translateDOM(root){
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = []; while (w.nextNode()) nodes.push(w.currentNode);
  nodes.forEach(n => { if (/[А-Яа-яЁё]/.test(n.nodeValue)) n.nodeValue = T(n.nodeValue); });
  root.querySelectorAll("[aria-label],[placeholder],[title]").forEach(el => ["aria-label","placeholder","title"].forEach(a => { const v = el.getAttribute(a); if (v && /[А-Яа-яЁё]/.test(v)) el.setAttribute(a, T(v)); }));
}
function setLang(l){
  l = l === "en" ? "en" : "ru";
  document.documentElement.lang = l;
  if (l === LANG) return;
  LANG = l;                 // переключение только ru → en (данные изначально на русском)
  translateData();
  translateDOM(document.body);
}
